    public static LocalizationService Instance { get; private set; } = null!;

    public LocalizationService()
    {
        Instance = this;
        SetLanguage(_currentLanguage);
    }

    public void SetLanguage(string language)
    {
        if (string.IsNullOrWhiteSpace(language)) language = "en";
        // normalize to short culture code (eg. "fr-FR" -> "fr")
        var code = language.Split(new[] { '-', '_' }, StringSplitOptions.RemoveEmptyEntries)[0].ToLowerInvariant();
        _currentLanguage = code;
        if (EmbeddedTranslations.TryGetValue(code, out var dict))
        {
            _currentTranslations = dict;
        }
        else
        {
            _currentTranslations = EmbeddedTranslations["en"];
        }
    }

    public string Get(string key)
    {
        if (_currentTranslations.TryGetValue(key, out var value))
        {
            return value;
        }
        // fallback to english if available
        if (EmbeddedTranslations.TryGetValue("en", out var en) && en.TryGetValue(key, out var enValue))
        {
            return enValue;
        }
        return key;
    }

    public string Get(string key, params object[] args)
    {
        var template = Get(key);
        try
        {
            return string.Format(template, args);
        }
        catch
        {
            return template;
        }
    }

    public IEnumerable<string> AvailableLanguages => EmbeddedTranslations.Keys;
